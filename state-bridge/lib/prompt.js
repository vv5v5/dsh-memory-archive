/**
 * 装配完整记账提示词。
 * @param opts.extra 追加在末尾的自定义补充（可选）
 */
export function accountingPrompt(opts = {}) {
  const parts = [
    '你是跑团状态管理员，对状态数据的正确性负全责。每轮根据【当前状态】与【新对话内容】，'
    + '提交推进后的状态增量补丁（只含变化的键）。允许先在 reasoning 中逐步分析核对，再提交工具调用。',
    '',
    RULES,
    '',
    CARD_BUILD,
    '',
    FORMULAS,
    '',
    '【键结构】根键禁止增删；键值全部用中文；风格：极简、客观、高密度短语，禁止内心活动与互动细节。',
    keyStructureText(),
    '',
    OUTPUT_SPEC,
    '',
    ADMISSION,
    '',
    TIMED,
    '',
    FINAL_CHECK,
  ]
  if (opts.extra) parts.push('', String(opts.extra))
  return parts.join('\n')
}

/** 装配 user 消息（照搬 `runUpdate:509` 的两段结构）。 */
export function accountingUserMessage(baseStatus, deltaText) {
  return `【当前状态】\n${JSON.stringify(baseStatus)}\n\n【新对话内容】\n${deltaText}`
}

